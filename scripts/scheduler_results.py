"""Durable pytest outcome events, separate from callable/relationship evidence."""
import json
import os
from pathlib import Path
import sys
import time
import faulthandler
import signal
import pytest
from retained_selection import canonical


def emit(kind, **values):
    path = os.environ.get('RELATION_EXECUTION_EVENTS')
    if not path:
        return
    row = {'kind': kind, 'at': time.time(), **values}
    payload = (json.dumps(row, ensure_ascii=False)+'\n').encode('utf-8')
    fd = os.open(path, os.O_WRONLY | os.O_APPEND | os.O_CREAT, 0o600)
    try:
        while payload:
            payload = payload[os.write(fd, payload):]
        os.fsync(fd)
    finally:
        os.close(fd)


def package_first():
    site = os.environ.get('RELATION_PACKAGE_SITE')
    if site:
        prefix=list(dict.fromkeys(filter(None,[os.environ.get('RELATION_PLUGIN_ROOT'),site])))
        sys.path[:] = [*prefix, *[p for p in sys.path if p not in prefix]]


@pytest.hookimpl(tryfirst=True)
def pytest_configure(config):
    package_first()
    config._execution_repo = Path(config.getoption('--api-relations-repo')).resolve()
    config._execution_nodes = {}
    stack = os.environ.get('RELATION_EXECUTION_STACK')
    if stack:
        config._execution_stack = open(stack, 'a', encoding='utf-8')
        faulthandler.register(signal.SIGUSR1, file=config._execution_stack, all_threads=True)
    emit('session_start', pid=os.getpid(), stack_ready=bool(stack))


@pytest.hookimpl(trylast=True)
def pytest_collection_finish(session):
    package_first()
    repo = session.config._execution_repo
    nodes = {item.nodeid: canonical(item, repo) for item in session.items}
    session.config._execution_nodes = nodes
    global _nodes
    _nodes = nodes
    emit('collection_finished', selected=list(nodes.values()))
    receipt = Path(session.config.getoption('--api-relations-out'))/'resume-selection.json'
    if receipt.exists() and not session.testsfailed:
        for node in json.loads(receipt.read_text(encoding='utf-8')).get('missing', []):
            emit('selection_missing', nodeid=node, detail='Exact inventory identity was not generated by this source/environment; see collection log and source provenance')


_nodes = {}


def pytest_collectreport(report):
    if report.failed or report.skipped:
        emit('collection_error' if report.failed else 'module_skipped',
             nodeid=report.nodeid, detail=str(report.longrepr))


@pytest.hookimpl(tryfirst=True)
def pytest_runtest_setup(item):
    package_first()


def pytest_runtest_logstart(nodeid, location):
    emit('test_start', nodeid=_nodes.get(nodeid, nodeid))


def pytest_runtest_logreport(report):
    emit('report', nodeid=_nodes.get(report.nodeid, report.nodeid),
         phase=report.when, outcome=report.outcome, duration=report.duration,
         detail=str(report.longrepr)[:64000] if report.longrepr else '',
         wasxfail=getattr(report, 'wasxfail', None))


def pytest_sessionfinish(session, exitstatus):
    emit('session_finished', exitstatus=int(exitstatus))


def pytest_unconfigure(config):
    stream = getattr(config, '_execution_stack', None)
    if stream:
        faulthandler.unregister(signal.SIGUSR1)
        stream.close()
